"""Build the report as blocks once, then render the same blocks to Markdown and HTML."""

from __future__ import annotations

import datetime as dt
import html
import os
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path

from navstress_eval.summary import summarize
from navstress_report import charts
from navstress_report.compare import Comparison
from navstress_report.data import AgentRun, Run

BEGIN = "<!-- navstress-report:begin -->"
END = "<!-- navstress-report:end -->"


@dataclass
class Link:
    text: str
    href: str  # relative to the Markdown file; HTML shows text only (bags aren't deployed)


@dataclass
class Block:
    kind: str  # h | p | note | img | table | video
    text: str = ""
    level: int = 2
    images: dict[str, Path] = field(default_factory=dict)
    headers: list[str] = field(default_factory=list)
    rows: list[list] = field(default_factory=list)


def _pct(rate: float | None) -> str:
    return "n/a" if rate is None else f"{rate:.0%}"


def _num(v: float | None, digits: int = 2) -> str:
    if v is None or v == float("inf"):
        return "n/a"
    return f"{v:.{digits}f}"


def _short(h: str) -> str:
    return h[:12]


def provenance(run: Run, results_label: str) -> str:
    m = run.metadata
    commit = str(m.get("git_commit", "unknown"))[:10]
    dirty = " (uncommitted changes)" if m.get("git_dirty") else ""
    parts = [
        f"Source: `{results_label}/results.csv`",
        f"git `{commit}`{dirty}",
        f"simulator `{m.get('simulator', '?')} {m.get('simulator_version', '')}`".rstrip(),
        f"ROS `{m.get('ros_distro', '?')}`",
        f"GPU `{m.get('gpu', '?')}`",
    ]
    if m.get("nav2_params_sha256"):
        parts.append(f"Nav2 params sha256 `{m['nav2_params_sha256'][:12]}`")
    if not m:
        parts.append("**run_metadata.json missing**")
    return " · ".join(parts)


class ReportBuilder:
    def __init__(self, md_path: Path, assets_dir: Path, results_label_root: str = "results"):
        self.md_path = md_path
        self.assets_dir = assets_dir
        self.root_label = results_label_root
        self.blocks: list[Block] = []

    def _rel(self, p: Path) -> str:
        return os.path.relpath(p, self.md_path.parent).replace(os.sep, "/")

    def add(self, **kw) -> None:
        self.blocks.append(Block(**kw))

    def header(self, title: str, runs: list[Run]) -> None:
        self.add(kind="h", level=2, text=title)
        now = dt.datetime.now(dt.UTC).strftime("%Y-%m-%d %H:%M UTC")
        self.add(
            kind="p",
            text=f"Generated by `navstress_report` at {now}. Every number below is read from "
            "the results files named under each table; runs are matched by config hash.",
        )
        if any(r.is_fakesim for r in runs):
            self.add(
                kind="note",
                text="FAKESIM: at least one run below was produced by the CI fake simulator "
                "(`navstress_fakesim`). Those numbers test the pipeline only; they are not "
                "Isaac Sim results and say nothing about Nav2's real behavior.",
            )

    def run_section(self, run: Run) -> None:
        label = f"{self.root_label}/{run.run_id}"
        title = f"Run `{run.run_id}`" + (f" ({run.label})" if run.label else "")
        self.add(kind="h", level=3, text=title)
        self.add(kind="p", text=provenance(run, label))
        stats = summarize(run.rows)
        fams = [
            {"family": s.family, "success_rate": s.success_rate, "successes": s.successes,
             "episodes": s.episodes}
            for s in stats.values()
        ]  # fmt: skip
        imgs = charts.success_by_family(
            fams, self.assets_dir, f"{run.run_id}_success", f"{label} · {len(run.rows)} episodes"
        )
        self.add(kind="img", text=f"Success rate by family for {run.run_id}", images=imgs)
        self.add(
            kind="table",
            headers=["family", "episodes", "success", "failure reasons", "collisions",
                     "min clearance (m)", "median time to goal (s)"],
            rows=[
                [s.family, s.episodes, f"{_pct(s.success_rate)} ({s.successes}/{s.episodes})",
                 ", ".join(f"{k} {v}" for k, v in s.failure_reasons.items()) or "-",
                 s.collisions, _num(s.min_clearance_m), _num(s.median_time_to_goal_s, 1)]
                for s in stats.values()
            ],
        )  # fmt: skip
        failed = [r for r in run.rows if not r["success"]]
        if failed:
            self.add(kind="h", level=4, text=f"Failed episodes ({len(failed)})")
            rows = []
            for r in sorted(failed, key=lambda r: (r["family"], r["scenario_id"])):
                bag = (
                    Link(r["bag_path"], self._rel(run.dir / r["bag_path"]))
                    if r["bag_path"]
                    else "-"
                )
                rows.append(
                    [r["scenario_id"], f"`{_short(r['config_hash'])}`", r["failure_reason"],
                     _num(r["min_clearance_m"]), r["collisions"], r["recoveries_triggered"], bag]
                )  # fmt: skip
            self.add(
                kind="table",
                headers=["scenario", "config hash", "reason", "min clearance (m)", "collisions",
                         "recoveries", "bag"],
                rows=rows,
            )  # fmt: skip

    def agent_section(self, agent: AgentRun) -> None:
        s = agent.summary
        self.add(kind="h", level=3, text=f"Agent run `{agent.run_id}`")
        self.add(
            kind="p",
            text=f"Source: `{self.root_label}/{agent.run_id}/agent_summary.json` and "
            f"`agent_log.jsonl` · {s.get('llm_calls', '?')} LLM calls · stopped: "
            f"{s.get('stop_reason', '?')}",
        )
        for rnd in s.get("rounds", []):
            n = rnd["round"]
            focus = rnd.get("focus_family")
            head = f"Round {n}" + (f": narrowing on `{focus}`" if focus else ": exploration")
            self.add(kind="h", level=4, text=head)
            batch = agent.batches.get(rnd["batch_run_id"])
            if batch is not None:
                self.add(kind="p", text=provenance(batch, f"{self.root_label}/{batch.run_id}"))
            self.add(
                kind="table",
                headers=["family", "hypothesis (from the LLM)", "episodes", "success"],
                rows=[
                    [fam, rnd["hypotheses"].get(fam, ""), st["episodes"],
                     f"{_pct(st['success_rate'])} ({st['successes']}/{st['episodes']})"]
                    for fam, st in rnd["summaries"].items()
                ],
            )  # fmt: skip
            sweep = rnd.get("sweep") or {}
            if rnd.get("curve") and sweep.get("parameter"):
                param = sweep["parameter"]
                imgs = charts.sweep(
                    rnd["curve"], param, rnd.get("boundary"), self.assets_dir,
                    f"{agent.run_id}_r{n}_sweep", f"{rnd['batch_run_id']} · family {focus}",
                )  # fmt: skip
                self.add(kind="img", text=f"Sweep of {param}", images=imgs)
                self.add(
                    kind="table",
                    headers=[param, "episodes", "success"],
                    rows=[[p["value"], p["episodes"],
                           f"{_pct(p['success_rate'])} ({p['successes']}/{p['episodes']})"]
                          for p in rnd["curve"]],
                )  # fmt: skip
                b = rnd.get("boundary") or {}
                if b.get("found"):
                    lo, hi = b["between"]
                    per = sorted({p["episodes"] for p in rnd["curve"]})
                    self.add(
                        kind="p",
                        text=f"Success rate crosses {b['threshold']:.0%} between `{param}` = "
                        f"{lo} and {hi} ({'/'.join(map(str, per))} episode(s) per value, so "
                        "the bracket, not a point estimate, is what the data supports).",
                    )
                else:
                    self.add(kind="p", text=f"No 50% crossing inside the swept range of {param}.")

    def comparison_section(self, cmp: Comparison) -> None:
        self.add(kind="h", level=3, text="Before / after (identical scenarios)")
        self.add(
            kind="p",
            text=f"Before: {provenance(cmp.before, f'{self.root_label}/{cmp.before.run_id}')}",
        )
        self.add(
            kind="p",
            text=f"After: {provenance(cmp.after, f'{self.root_label}/{cmp.after.run_id}')}",
        )
        unmatched = len(cmp.only_before) + len(cmp.only_after)
        self.add(
            kind="p",
            text=f"{len(cmp.matched_hashes)} scenarios matched by config hash; "
            f"{unmatched} unmatched (excluded from every number in this section).",
        )
        imgs = charts.before_after(
            cmp.families, self.assets_dir, f"{cmp.before.run_id}_vs_{cmp.after.run_id}",
            f"{cmp.before.run_id} → {cmp.after.run_id}",
        )  # fmt: skip
        self.add(kind="img", text="Success rate before and after", images=imgs)
        self.add(
            kind="table",
            headers=["family", "episodes", "before", "after", "collisions before",
                     "collisions after"],
            rows=[[f["family"], f["episodes"], _pct(f["before_success_rate"]),
                   _pct(f["after_success_rate"]), f["before_collisions"], f["after_collisions"]]
                  for f in cmp.families],
        )  # fmt: skip
        for title, items in (("Regressions (passed before, fail after)", cmp.regressions),
                             ("Fixed (failed before, pass after)", cmp.fixed)):  # fmt: skip
            self.add(kind="h", level=4, text=f"{title}: {len(items)}")
            if items:
                self.add(
                    kind="table",
                    headers=["scenario", "family", "config hash", "before", "after"],
                    rows=[[i["scenario_id"], i["family"], f"`{_short(i['config_hash'])}`",
                           i["before"], i["after"]] for i in items],
                )  # fmt: skip

    def videos(self, videos: list[tuple[Path, str]]) -> None:
        if not videos:
            return
        self.add(kind="h", level=3, text="Episode videos")
        for path, caption in videos:
            self.add(kind="video", text=caption, images={"src": path})


# ----------------------------------------------------------------------------- Markdown


def _md_cell(c) -> str:
    if isinstance(c, Link):
        return f"[{c.text}]({c.href})"
    return str(c).replace("|", "\\|").replace("\n", " ")


def to_markdown(blocks: list[Block], md_path: Path) -> str:
    out = []
    for b in blocks:
        if b.kind == "h":
            out.append("#" * b.level + " " + b.text)
        elif b.kind == "p":
            out.append(b.text)
        elif b.kind == "note":
            out.append("> **Note:** " + b.text)
        elif b.kind == "img":
            light = os.path.relpath(b.images["light"], md_path.parent).replace(os.sep, "/")
            dark = os.path.relpath(b.images["dark"], md_path.parent).replace(os.sep, "/")
            out.append(
                f'<picture><source media="(prefers-color-scheme: dark)" srcset="{dark}">'
                f'<img src="{light}" alt="{html.escape(b.text)}" width="640"></picture>'
            )
        elif b.kind == "table":
            out.append("| " + " | ".join(b.headers) + " |")
            out.append("|" + "---|" * len(b.headers))
            out.extend("| " + " | ".join(_md_cell(c) for c in row) + " |" for row in b.rows)
        elif b.kind == "video":
            src = os.path.relpath(b.images["src"], md_path.parent).replace(os.sep, "/")
            out.append(f"[{b.text}]({src})")
        out.append("")
    return "\n".join(out)


def write_markdown(md_path: Path, body: str) -> None:
    """Replace only the generated section, so hand-written sections survive reruns."""
    section = f"{BEGIN}\n{body.rstrip()}\n{END}\n"
    if md_path.exists():
        text = md_path.read_text()
        if BEGIN in text and END in text:
            pre, rest = text.split(BEGIN, 1)
            post = rest.split(END, 1)[1]
            md_path.write_text(pre + section + post.lstrip("\n"))
            return
        md_path.write_text(text.rstrip() + "\n\n" + section)
        return
    md_path.parent.mkdir(parents=True, exist_ok=True)
    md_path.write_text("# Results\n\n" + section)


# ----------------------------------------------------------------------------- HTML

_CODE = re.compile(r"`([^`]+)`")
_BOLD = re.compile(r"\*\*([^*]+)\*\*")


def _inline(text: str) -> str:
    t = html.escape(text)
    t = _CODE.sub(r"<code>\1</code>", t)
    return _BOLD.sub(r"<strong>\1</strong>", t)


