def to_html(blocks: list[Block], site_dir: Path, title: str) -> str:
    img_dir = site_dir / "img"
    img_dir.mkdir(parents=True, exist_ok=True)
    body = [f"<h1>{html.escape(title)}</h1>"]
    for b in blocks:
        if b.kind == "h":
            lvl = min(b.level, 4)
            body.append(f"<h{lvl}>{_inline(b.text)}</h{lvl}>")
        elif b.kind == "p":
            body.append(f"<p>{_inline(b.text)}</p>")
        elif b.kind == "note":
            body.append(f'<p class="note"><strong>Note:</strong> {_inline(b.text)}</p>')
        elif b.kind == "img":
            for p in b.images.values():
                shutil.copy2(p, img_dir / p.name)
            light, dark = b.images["light"].name, b.images["dark"].name
            body.append(
                f'<picture><source media="(prefers-color-scheme: dark)" srcset="img/{dark}">'
                f'<img src="img/{light}" alt="{html.escape(b.text)}"></picture>'
            )
        elif b.kind == "table":
            head = "".join(f"<th>{html.escape(h)}</th>" for h in b.headers)
            rows = "".join(
                "<tr>"
                + "".join(
                    f"<td>{_inline(c.text if isinstance(c, Link) else str(c))}</td>" for c in row
                )
                + "</tr>"
                for row in b.rows
            )
            body.append(
                f'<div class="scroll"><table><thead><tr>{head}</tr></thead>'
                f"<tbody>{rows}</tbody></table></div>"
            )
        elif b.kind == "video":
            src = b.images["src"]
            (site_dir / "video").mkdir(exist_ok=True)
            shutil.copy2(src, site_dir / "video" / src.name)
            body.append(
                f'<figure><video controls preload="metadata" src="video/{src.name}"></video>'
                f"<figcaption>{_inline(b.text)}</figcaption></figure>"
            )
    return (
        '<!doctype html>\n<html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>{html.escape(title)}</title><style>{_CSS}</style></head>"
        f"<body><main>{''.join(body)}</main></body></html>\n"
    )
